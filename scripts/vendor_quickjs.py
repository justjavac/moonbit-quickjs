#!/usr/bin/env python3
"""Vendor QuickJS C sources into ``src/`` and apply the MSVC compatibility patches.

The bindings no longer link a prebuilt quickjs.lib / libquickjs.a. Instead the
QuickJS engine is compiled from these sources as MoonBit ``native-stub`` files.

Usage::

    python scripts/vendor_quickjs.py --source /path/to/quickjs-upstream
    python scripts/vendor_quickjs.py --check --source /path/to/quickjs-upstream

The default ``--source`` is ``target/quickjs-src`` (a gitignored local checkout
of https://github.com/bellard/quickjs.git). Upstream revision is recorded in
``UPSTREAM_TAG`` below; ``--source`` must match it.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
DEFAULT_SOURCE = ROOT / "target" / "quickjs-src"

UPSTREAM_URL = "https://github.com/bellard/quickjs.git"
UPSTREAM_TAG = "d7ae12ae71dfd6ab2997527d295014a8996fa0f9"

# Only the engine core is needed; quickjs-libc.c / qjs.c / qjsc.c are excluded.
C_SOURCES = [
    "quickjs.c",
    "cutils.c",
    "dtoa.c",
    "libregexp.c",
    "libunicode.c",
]

# src/quickjs.h is deliberately NOT overwritten: it is the exported header with
# the MSVC fix already applied (`return v;` instead of `return (JSValue)v;`).
HEADERS = [
    "cutils.h",
    "dtoa.h",
    "libregexp-opcode.h",
    "libregexp.h",
    "libunicode-table.h",
    "libunicode.h",
    "list.h",
    "quickjs-atom.h",
    "quickjs-opcode.h",
]

# These are the same source transformations that the old CMake-based
# libquickjs Windows build applied before producing quickjs.lib. They are
# harmless on GCC/Clang, so the vendored tree is identical on every platform.
QUICKJS_C_PATCHES = [
    (
        "#if defined(EMSCRIPTEN)\n#define DIRECT_DISPATCH  0\n#else\n#define DIRECT_DISPATCH  1\n#endif",
        "#if defined(EMSCRIPTEN) || defined(_WIN32)\n#define DIRECT_DISPATCH  0\n#else\n#define DIRECT_DISPATCH  1\n#endif",
    ),
    ("-1.0 / 0.0", "-INFINITY"),
    ("1.0 / 0.0", "INFINITY"),
    (
        "/* define to include Atomics.* operations which depend on the OS\n"
        "   threads */\n#if !defined(EMSCRIPTEN)\n#define CONFIG_ATOMICS\n#endif",
        "/* define to include Atomics.* operations which depend on the OS\n"
        "   threads */\n#if !defined(EMSCRIPTEN) && !defined(_WIN32)\n#define CONFIG_ATOMICS\n#endif",
    ),
    ("prop = js_symbol_to_atom(ctx, (JSValue)name);", "prop = js_symbol_to_atom(ctx, name);"),
    (
        "prs = find_own_property(&pr, p, js_symbol_to_atom(ctx, (JSValue)brand));",
        "prs = find_own_property(&pr, p, js_symbol_to_atom(ctx, brand));",
    ),
    ("val = (JSValueConst)JS_NewUint32(ctx, array_length);", "val = JS_NewUint32(ctx, array_length);"),
    ("sf->cur_func = (JSValue)func_obj;", "sf->cur_func = func_obj;"),
    ("JS_FreeValue(ctx, (JSValue)args[0]);", "JS_FreeValue(ctx, args[0]);"),
    ("JS_FreeValue(ctx, (JSValue)args[1]);", "JS_FreeValue(ctx, args[1]);"),
    ("args[args_len++] = (JSValueConst)str;", "args[args_len++] = str;"),
    ("return (JSValue)val;", "return val;"),
    (
        "return (JSValueConst)map_normalize_key(ctx, (JSValue)key);",
        "return map_normalize_key(ctx, key);",
    ),
    ("args[2] = (JSValue)this_val;", "args[2] = this_val;"),
    (
        "resolve_element_data[1] = (JSValueConst)JS_NewInt32(ctx, index);",
        "resolve_element_data[1] = JS_NewInt32(ctx, index);",
    ),
    (
        "func_data[0] = (JSValueConst)JS_NewBool(ctx, done);",
        "func_data[0] = JS_NewBool(ctx, done);",
    ),
    (
        "static void __attribute((unused)) dump_token(JSParseState *s,",
        "static void dump_token(JSParseState *s,",
    ),
    # MSVC treats this 3-bit enum bitfield as signed, breaking closure dispatch.
    ("    JSClosureTypeEnum closure_type : 3;", "    uint8_t closure_type : 3;"),
    ("JS_FreeValue(ctx, (JSValue)argv[0]);", "JS_FreeValue(ctx, argv[0]);"),
    ("JS_FreeValue(ctx, (JSValue)argv[1]);", "JS_FreeValue(ctx, argv[1]);"),
]

BUILD_HEADER = """/* Generated by scripts/vendor_quickjs.py -- do not edit by hand.
 *
 * Injected at the top of every vendored QuickJS translation unit so that the
 * engine builds correctly with both MSVC (cl.exe) and GCC/Clang, without any
 * platform-specific compiler flags in moon.pkg.
 */
#ifndef MOONBIT_QUICKJS_BUILD_H
#define MOONBIT_QUICKJS_BUILD_H

#ifndef CONFIG_VERSION
#define CONFIG_VERSION "{version}"
#endif

#if defined(_MSC_VER)
#ifndef _CRT_SECURE_NO_WARNINGS
#define _CRT_SECURE_NO_WARNINGS
#endif
#ifndef _CRT_NONSTDC_NO_WARNINGS
#define _CRT_NONSTDC_NO_WARNINGS
#endif
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include "compat/msvc_compat.h"
#endif

#endif /* MOONBIT_QUICKJS_BUILD_H */
"""

MSVC_COMPAT_HEADER = """/* From justjavac/libquickjs compat/msvc_compat.h (MIT license).
 * Force-included on MSVC through quickjs_build.h.
 */
#ifndef LIBQUICKJS_MSVC_COMPAT_H
#define LIBQUICKJS_MSVC_COMPAT_H

#if defined(_MSC_VER)

#include <intrin.h>
#include <stdint.h>

#ifndef __attribute__
#define __attribute__(x)
#endif

#ifndef __builtin_expect
#define __builtin_expect(x, expected) (x)
#endif

#ifndef __builtin_frame_address
#define __builtin_frame_address(level) _AddressOfReturnAddress()
#endif

static __forceinline int libquickjs_builtin_clz(unsigned int value) {
  unsigned long index;
  _BitScanReverse(&index, value);
  return 31 - (int)index;
}

static __forceinline int libquickjs_builtin_clzll(uint64_t value) {
  unsigned long index;
#if defined(_M_X64) || defined(_M_ARM64)
  _BitScanReverse64(&index, value);
  return 63 - (int)index;
#else
  if (value >> 32) {
    _BitScanReverse(&index, (unsigned long)(value >> 32));
    return 31 - (int)index;
  }
  _BitScanReverse(&index, (unsigned long)value);
  return 63 - (int)index;
#endif
}

static __forceinline int libquickjs_builtin_ctz(unsigned int value) {
  unsigned long index;
  _BitScanForward(&index, value);
  return (int)index;
}

static __forceinline int libquickjs_builtin_ctzll(uint64_t value) {
  unsigned long index;
#if defined(_M_X64) || defined(_M_ARM64)
  _BitScanForward64(&index, value);
  return (int)index;
#else
  if ((uint32_t)value != 0) {
    _BitScanForward(&index, (unsigned long)value);
    return (int)index;
  }
  _BitScanForward(&index, (unsigned long)(value >> 32));
  return 32 + (int)index;
#endif
}

#define __builtin_clz(value) libquickjs_builtin_clz(value)
#define __builtin_clzll(value) libquickjs_builtin_clzll(value)
#define __builtin_ctz(value) libquickjs_builtin_ctz(value)
#define __builtin_ctzll(value) libquickjs_builtin_ctzll(value)

#endif

#endif
"""

SYS_TIME_HEADER = """/* Cross-platform shim for <sys/time.h>, from justjavac/libquickjs
 * compat/sys/time.h (MIT license), extended with a Unix passthrough.
 */
#ifndef LIBQUICKJS_COMPAT_SYS_TIME_H
#define LIBQUICKJS_COMPAT_SYS_TIME_H

#if defined(_WIN32)

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif

#include <stdint.h>
#include <winsock2.h>
#include <windows.h>

static inline int gettimeofday(struct timeval *tv, void *tz) {
  FILETIME file_time;
  ULARGE_INTEGER ticks;
  const uint64_t windows_to_unix_epoch = 116444736000000000ULL;
  uint64_t unix_time_100ns;

  if (!tv) {
    return -1;
  }

  (void)tz;

  GetSystemTimeAsFileTime(&file_time);
  ticks.LowPart = file_time.dwLowDateTime;
  ticks.HighPart = file_time.dwHighDateTime;

  unix_time_100ns = ticks.QuadPart - windows_to_unix_epoch;
  tv->tv_sec = (long)(unix_time_100ns / 10000000ULL);
  tv->tv_usec = (long)((unix_time_100ns % 10000000ULL) / 10ULL);
  return 0;
}

#else

#include <sys/time.h>

#endif

#endif
"""


def patch_quickjs_c(text: str) -> str:
    for old, new in QUICKJS_C_PATCHES:
        count = text.count(old)
        if count == 0:
            raise SystemExit(
                "vendor_quickjs.py: upstream quickjs.c no longer matches patch:\n"
                + old[:100]
            )
        text = text.replace(old, new)
    return text


def inject_build_header(text: str) -> str:
    marker = '#include "quickjs_build.h"\n'
    if marker in text:
        return text
    index = text.find("#include")
    if index < 0:
        raise SystemExit("vendor_quickjs.py: no #include found in C source")
    return text[:index] + marker + "\n" + text[index:]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify src/ matches a fresh vendor run without writing anything",
    )
    args = parser.parse_args()

    source: Path = args.source.resolve()
    if not (source / "quickjs.c").exists():
        print(
            f"QuickJS upstream checkout not found at {source}.\n"
            f"Clone it with:\n"
            f"  git clone {UPSTREAM_URL} {source}\n"
            f"  git -C {source} checkout {UPSTREAM_TAG}",
            file=sys.stderr,
        )
        return 1

    version = (source / "VERSION").read_text(encoding="utf-8").strip()
    generated: dict[Path, str] = {}

    for name in HEADERS:
        generated[SRC / name] = (source / name).read_text(encoding="utf-8")

    for name in C_SOURCES:
        text = (source / name).read_text(encoding="utf-8")
        if "#include <sys/time.h>" in text:
            text = text.replace(
                "#include <sys/time.h>", '#include "compat/sys/time.h"'
            )
        if name == "quickjs.c":
            text = patch_quickjs_c(text)
        generated[SRC / name] = inject_build_header(text)

    generated[SRC / "quickjs_build.h"] = BUILD_HEADER.format(version=version)
    generated[SRC / "compat" / "msvc_compat.h"] = MSVC_COMPAT_HEADER
    generated[SRC / "compat" / "sys" / "time.h"] = SYS_TIME_HEADER

    exported_header = (SRC / "quickjs.h").read_text(encoding="utf-8")
    if "return (JSValue)v;" in exported_header:
        raise SystemExit(
            "vendor_quickjs.py: src/quickjs.h lost its MSVC fix "
            "(`return v;`); re-apply it or regenerate the exported header."
        )

    changed = []
    for path, content in generated.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content.replace("\r\n", "\n") and current != content:
            changed.append(path.relative_to(ROOT).as_posix())

    if args.check:
        if changed:
            print("out of date:", *changed, sep="\n  ")
            return 1
        print(f"vendored QuickJS {version} is up to date ({len(generated)} files)")
        return 0

    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"vendored QuickJS {version} from {UPSTREAM_TAG}")
    print(f"  {len(C_SOURCES)} C sources + {len(HEADERS)} headers + 3 build shims -> src/")
    print(f"  updated {len(changed)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
